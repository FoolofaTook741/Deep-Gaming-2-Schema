function impulse.RPAnnouncement(ply)
	if ply:Team() != TEAM_CP and ply:Team() != TEAM_OTA then
		ply:Notify("You must be a Civil Protection or Overwatch Transhuman Arm to use this button.")
		return false
	end

	if not ply:IsCPCommand() then
		ply:Notify("You are not a commanding unit! You cannot use these buttons.")
		return false
	end

	if impulse.RPAnnouncementDelay > CurTime() then
		ply:Notify("Please wait " .. string.NiceTime(impulse.RPAnnouncementDelay - CurTime()) .. " to announce something again.")
		return false
	end

	impulse.RPAnnouncementDelay = CurTime() + 90
	return true
end

