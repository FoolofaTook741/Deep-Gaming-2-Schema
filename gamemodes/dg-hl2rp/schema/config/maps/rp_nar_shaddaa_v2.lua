		3601,
		3600,
		1235,
		3608,
		1235,
		
	}

	for v,k in pairs(removeMe) do
		local ent = ents.GetMapCreatedEntity(k)

		if ent and IsValid(ent) then
			ent:Remove()
		end
	end
